#!/usr/bin/env python3
"""jsc-route-matrix.py - frozen instrument for R64-C1 (depth, capability acquisition).

Round 64. The jsc2js route (S125 README, S129 release inventory; upstream commit
01fc264d22055865a460b322399a15d84b71f5aa) has three stages:

  1. dump    patched d8: `d8 -e "loadjsc('<artifact>')"` prints V8 Ignition text
  2. view8   View8/view8.py --disassembled DUMP OUT.js  (reconstruction)
  3. check   `node --check OUT.js` (is the reconstruction parseable JavaScript?)

The matrix is 2 artifacts x 3 d8 builds x 3 repetitions = 18 runs:

  artifacts  probe   = a code cache generated by Electron 42.2.0 run-as-node
                       (V8 14.8.178.14) from tools/round-64/mkcache.js (committed)
             typora  = atom.compiled.dist.jsc extracted from
                       /usr/share/typora/resources/app.asar (sha256 pinned below)
  d8 builds  D1 = jsc2js 14.8.178.14 (the Electron 42.2.0 V8 version string)
             D2 = jsc2js 14.8.178.1  (same minor, different build)
             D3 = jsc2js 14.7.173    (previous minor)

Predicate (the same sentence appears in claims.json, the plan and the receipt):
  R64-C1 is verified iff all 18 runs reproduce the frozen predicted label of their
  cell (dump|view8|check), with every input and binary sha256 equal to its pin.

Labels: dump-ok | dump-exit-<code> | dump-empty | dump-timeout;
        view8-ok | view8-exit-<code> | view8-empty | view8-skipped;
        node-pass | node-fail | node-skipped.  A signal death is 128+signal (134 =
        SIGABRT, 139 = SIGSEGV), the value a POSIX shell reports for it.

Exit: 0 verified (18/18); 1 claim not verified (any mismatch, including the
--skip-run do-nothing control, which records every cell as not-run); 2
could-not-evaluate (missing input, pin mismatch, or missing tool).

--selftest runs the classifiers and the verdict arithmetic over in-memory
fixtures (no d8, no network, no writes) and asserts each label and exit class.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path

TOOL = "tools/round-64/jsc-route-matrix.py"
PREDICATE = (
    "R64-C1 is verified iff all 18 runs reproduce the frozen predicted label of their "
    "cell (dump|view8|check), with every input and binary sha256 equal to its pin."
)
REPS = 3

# name -> sha256. Binaries and inputs are checked before any run.
PINS = {
    "probe": "a86f6ea04b95c9796b87b24aa8a414aba97b4468a6c39bb2298310e28fd1d710",
    "typora": "6a0cb7b32270498ed190c589ca29c990a0e4b5f06f0cd6a5516e19a715c2dfe9",
    "D1": "bc70d3c057c5468611400a9b93a339ca2751c570d64337a2075b0d6bef835331",
    "D2": "4060ff2ea9e0955dd1dee27e3b77b3013140368d370833e4a99184a1f1ae49b8",
    "D3": "c240ffaef3b9022a44f36e35c124400c225906e5e9dd6f373b4323ba62bcdcf2",
    "D1-snapshot": "b5c418dc0c6006d8dc6f4ac9981182eecf783cd892ae4c4b4ba16977c17bf2bb",
    "D1-icudtl": "c5da2fc389d1bb0ecb13fe22a8e069b7abc491f8aa5d16eb65d4ff32c85a46b6",
    "view8.py": "b3123e4a4651cbd7d810e14c6ac3ec45380e1b50580a4d194eb321e37171918c",
}

# The frozen predictions, written before any matrix run. A cell whose label differs
# from its prediction is a finding; it is never re-predicted.
PREDICTED = {
    ("probe", "D1"): "dump-ok|view8-ok|node-fail",
    ("probe", "D2"): "dump-ok|view8-ok|node-fail",
    ("probe", "D3"): "dump-exit-139|view8-skipped|node-skipped",
    ("typora", "D1"): "dump-exit-134|view8-skipped|node-skipped",
    ("typora", "D2"): "dump-exit-134|view8-skipped|node-skipped",
    ("typora", "D3"): "dump-exit-134|view8-skipped|node-skipped",
}

SFI_RE = re.compile(rb"\[SharedFunctionInfo\]")


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def norm_rc(rc: int) -> int:
    """Python reports a signal death as -signo; a POSIX shell reports 128+signo."""
    return 128 - rc if rc < 0 else rc


def classify_dump(rc, stdout: bytes) -> str:
    if rc == "timeout":
        return "dump-timeout"
    code = norm_rc(rc)
    if code != 0:
        return f"dump-exit-{code}"
    if not SFI_RE.search(stdout):
        return "dump-empty"
    return "dump-ok"


def classify_view8(rc: int, out_size: int | None) -> str:
    code = norm_rc(rc)
    if code != 0:
        return f"view8-exit-{code}"
    if not out_size:
        return "view8-empty"
    return "view8-ok"


def classify_check(rc: int) -> str:
    return "node-pass" if norm_rc(rc) == 0 else "node-fail"


def compose(dump: str, view8: str | None, check: str | None) -> str:
    v = view8 if view8 is not None else "view8-skipped"
    c = check if check is not None else "node-skipped"
    return f"{dump}|{v}|{c}"


def verdict(labels: dict) -> tuple[int, dict]:
    """labels: {(artifact, build, rep): label}. Returns (exit, summary)."""
    total = len(PREDICTED) * REPS
    matches = 0
    mismatches = []
    for (artifact, build), predicted in PREDICTED.items():
        for rep in range(1, REPS + 1):
            got = labels.get((artifact, build, rep), "not-run")
            if got == predicted:
                matches += 1
            else:
                mismatches.append({"cell": [artifact, build], "rep": rep,
                                   "predicted": predicted, "observed": got})
    ok = matches == total
    return (0 if ok else 1), {"runs_total": total, "runs_matching": matches,
                              "mismatches": mismatches, "verified": ok}


def check_pins(args) -> str | None:
    """Return an error message when an input or binary does not match its pin."""
    inputs = {"probe": Path(args.probe), "typora": Path(args.typora)}
    for name, p in inputs.items():
        if not p.is_file():
            return f"missing input {name}: {p}"
        if sha256_file(p) != PINS[name]:
            return f"pin mismatch {name}: {p}"
    builds = {"D1": Path(args.d8_match), "D2": Path(args.d8_neighbour),
              "D3": Path(args.d8_cross)}
    for name, d in builds.items():
        d8 = d / "d8"
        if not d8.is_file():
            return f"missing d8 {name}: {d8}"
        if sha256_file(d8) != PINS[name]:
            return f"pin mismatch d8 {name}: {d8}"
    d1 = builds["D1"]
    for fname, key in (("snapshot_blob.bin", "D1-snapshot"), ("icudtl.dat", "D1-icudtl")):
        f = d1 / fname
        if not f.is_file() or sha256_file(f) != PINS[key]:
            return f"pin mismatch D1 {fname}"
    view8 = Path(args.view8_dir) / "view8.py"
    if not view8.is_file() or sha256_file(view8) != PINS["view8.py"]:
        return f"pin mismatch view8.py: {view8}"
    return None


def run_cell(d8: Path, artifact: Path, cell: Path, timeout: int):
    try:
        r = subprocess.run([str(d8), "-e", f"loadjsc('{artifact}')"],
                           cwd=str(cell), capture_output=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return "timeout", b"", b""
    return r.returncode, r.stdout, r.stderr


def run_matrix(args) -> int:
    error = check_pins(args)
    if error:
        print(f"{TOOL}: {error}", file=sys.stderr)
        return 2
    builds = {"D1": Path(args.d8_match), "D2": Path(args.d8_neighbour),
              "D3": Path(args.d8_cross)}
    inputs = {"probe": Path(args.probe), "typora": Path(args.typora)}
    view8_dir = Path(args.view8_dir)
    work_root = Path(args.work)
    work_root.mkdir(parents=True, exist_ok=True)
    labels: dict = {}
    receipts = []
    for (artifact, build) in PREDICTED:
        for rep in range(1, REPS + 1):
            cell = work_root / f"{artifact}-{build}-r{rep}"
            cell.mkdir(parents=True, exist_ok=True)
            rc, out, err = run_cell(builds[build] / "d8", inputs[artifact], cell,
                                    args.timeout)
            (cell / "dump.txt").write_bytes(out)
            (cell / "dump.err").write_bytes(err)
            dump = classify_dump(rc, out)
            view8 = check = None
            out_size = None
            if dump == "dump-ok":
                out_js = cell / "reconstruction.js"
                r = subprocess.run(
                    [args.python, "view8.py", "--disassembled",
                     str(cell / "dump.txt"), str(out_js)],
                    cwd=str(view8_dir), capture_output=True, timeout=600)
                out_size = out_js.stat().st_size if out_js.exists() else None
                view8 = classify_view8(r.returncode, out_size)
                if view8 == "view8-ok":
                    c = subprocess.run([args.node, "--check", str(out_js)],
                                       capture_output=True, timeout=120)
                    check = classify_check(c.returncode)
            label = compose(dump, view8, check)
            labels[(artifact, build, rep)] = label
            receipts.append({"artifact": artifact, "build": build, "rep": rep,
                             "dump_rc": rc if isinstance(rc, str) else norm_rc(rc),
                             "dump_bytes": len(out), "view8_out_bytes": out_size,
                             "label": label})
    return emit(labels, receipts, False, args)


def emit(labels: dict, receipts: list, skip_run: bool, args) -> int:
    exit_code, summary = verdict(labels)
    result = {"tool": TOOL, "predicate": PREDICATE, "skip_run": skip_run,
              "predicted": {f"{a}|{b}": v for (a, b), v in PREDICTED.items()},
              "receipts": receipts, **summary, "exit": exit_code}
    text = json.dumps(result, indent=1, sort_keys=True) + "\n"
    if args.out:
        Path(args.out).write_text(text, encoding="utf-8")
    sys.stdout.write(text)
    return exit_code


def selftest() -> int:
    cases = []

    def check(name, got, want):
        cases.append((name, got == want, got, want))

    dump_ok = b"Start SharedFunctionInfo\n0x1: [SharedFunctionInfo] in OldSpace\n"
    check("dump-ok", classify_dump(0, dump_ok), "dump-ok")
    check("dump-empty-rc0", classify_dump(0, b""), "dump-empty")
    check("dump-sigabrt", classify_dump(-6, b""), "dump-exit-134")
    check("dump-sigsegv", classify_dump(-11, b""), "dump-exit-139")
    check("dump-exit-1", classify_dump(1, dump_ok), "dump-exit-1")
    check("dump-timeout", classify_dump("timeout", b""), "dump-timeout")
    check("view8-ok", classify_view8(0, 213), "view8-ok")
    check("view8-empty", classify_view8(0, 0), "view8-empty")
    check("view8-exit", classify_view8(1, 213), "view8-exit-1")
    check("check-pass", classify_check(0), "node-pass")
    check("check-fail", classify_check(1), "node-fail")
    check("compose-full", compose("dump-ok", "view8-ok", "node-fail"),
          "dump-ok|view8-ok|node-fail")
    check("compose-skipped", compose("dump-exit-134", None, None),
          "dump-exit-134|view8-skipped|node-skipped")
    full = {(a, b, r): v for (a, b), v in PREDICTED.items() for r in range(1, REPS + 1)}
    check("verdict-all-match", verdict(full)[0], 0)
    check("verdict-do-nothing-exit", verdict({})[0], 1)
    check("verdict-do-nothing-count", verdict({})[1]["runs_matching"], 0)
    one_off = dict(full)
    one_off[("typora", "D2", 2)] = "dump-ok|view8-ok|node-pass"
    check("verdict-one-mismatch-exit", verdict(one_off)[0], 1)
    check("verdict-one-mismatch-count", verdict(one_off)[1]["runs_matching"], 17)
    fake_green = {k: "dump-ok|view8-ok|node-pass" for k in full}
    check("verdict-fake-green-count", verdict(fake_green)[1]["runs_matching"], 0)

    import os
    import tempfile

    class Args:
        pass

    with tempfile.TemporaryDirectory(dir=os.environ.get("TMPDIR") or None) as scratch:
        wrong = Path(scratch) / "wrong.jsc"
        wrong.write_bytes(b"not the pinned artifact")
        args = Args()
        args.probe = str(wrong)
        args.typora = str(Path(scratch) / "absent.jsc")
        args.d8_match = args.d8_neighbour = args.d8_cross = scratch
        args.view8_dir = scratch
        check("pin-probe-mismatch", (check_pins(args) or "").split(":")[0],
              "pin mismatch probe")
        args.probe = str(wrong.with_name("absent-probe.jsc"))
        check("pin-probe-missing", (check_pins(args) or "").split(":")[0],
              "missing input probe")
        args.probe = str(wrong)
        check("pin-typora-missing-after-probe", (check_pins(args) or "").split(":")[0],
              "pin mismatch probe")

    failures = [c for c in cases if not c[1]]
    for name, ok, got, want in cases:
        print(f"{'PASS' if ok else 'FAIL'} {name} got={got!r} want={want!r}")
    print(f"SELFTEST {'CLEAN' if not failures else 'FAILED'} "
          f"cases={len(cases)} failures={len(failures)}")
    return 0 if not failures else 1


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--selftest", action="store_true")
    ap.add_argument("--skip-run", action="store_true",
                    help="do-nothing control: every cell recorded as not-run")
    ap.add_argument("--probe")
    ap.add_argument("--typora")
    ap.add_argument("--d8-match", dest="d8_match")
    ap.add_argument("--d8-neighbour", dest="d8_neighbour")
    ap.add_argument("--d8-cross", dest="d8_cross")
    ap.add_argument("--view8-dir", dest="view8_dir")
    ap.add_argument("--python", default=sys.executable)
    ap.add_argument("--node", default="node")
    ap.add_argument("--work", help="explicit scratch root for the run cells")
    ap.add_argument("--timeout", type=int, default=600)
    ap.add_argument("--out")
    args = ap.parse_args(argv)
    if args.selftest:
        return selftest()
    if args.skip_run:
        return emit({}, [], True, args)
    required = ("probe", "typora", "d8_match", "d8_neighbour", "d8_cross",
                "view8_dir", "work")
    missing = [k for k in required if not getattr(args, k)]
    if missing:
        ap.error("missing: " + ", ".join("--" + m.replace("_", "-") for m in missing))
    return run_matrix(args)


if __name__ == "__main__":
    sys.exit(main())
