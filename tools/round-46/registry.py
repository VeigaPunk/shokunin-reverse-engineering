def _rows_index(lines):
    data = [i for i, c in enumerate(lines) if not is_sep(c)]
    return data[1:] if data else []


def m_fenced(mid):
    body = [l for l in mid.splitlines() if l.strip().startswith("|")]
    if not body:
        raise ValueError("no table rows")
    head = mid.splitlines()[0] if mid.splitlines() else ""
    rest = [l for l in mid.splitlines() if not l.strip().startswith("|")]
    return "\n```\n" + "\n".join(body) + "\n```\n" + "\n".join(rest) + "\n"


def m_off_section(skill, spec):
    mid, err = split_section(skill, spec)
    if err:
        raise ValueError(err)
    head, tail = spec["markers"]
    table = [l for l in mid.splitlines() if l.strip().startswith("|")]
    rest = [l for l in mid.splitlines() if not l.strip().startswith("|")]
    before = "\n".join(table) + "\n\n"
    return skill.replace(head + mid + tail, before + head + "\n".join(rest) + tail, 1)


def m_substring_cell(skill, spec):
    def fix(m):
        return "see " + m.group(0) + " (wrapper)"
    mid, err = split_section(skill, spec)
    if err:
        raise ValueError(err)
    new = re.sub(r"\|\s*(`tools/[A-Za-z0-9._/-]+\.(?:py|sh)`)\s*\|",
                 lambda m: "| see " + m.group(1) + " (wrapper) |", mid)
    if new == mid:
        raise ValueError("no tool cell rewritten")
    return skill.replace(mid, new, 1)


def m_prose_exit(skill, spec):
    mid, err = split_section(skill, spec)
    if err:
        raise ValueError(err)
    new = re.sub(r"\|[^|\n]*\b0=[^|\n]*\|", "| 0 rows, 1 column, 2 bytes |", mid, count=1)
    if new == mid:
        new = re.sub(r"\|[^|\n]*`?0`?[^|\n]*\|", "| 0 rows, 1 column, 2 bytes |", mid, count=3)
    if new == mid:
        raise ValueError("no verdict-map cell rewritten")
    return skill.replace(mid, new, 1)


def m_html_comment(skill, spec):
    mid, err = split_section(skill, spec)
    if err:
        raise ValueError(err)
    body = [l for l in mid.splitlines() if l.strip().startswith("|")]
    rest = [l for l in mid.splitlines() if not l.strip().startswith("|")]
    new = "<!--\n" + "\n".join(body) + "\n-->\n" + "\n".join(rest) + "\n"
    return skill.replace(mid, new, 1)


def m_thin_shadow(skill, spec):
    mid, err = split_section(skill, spec)
    if err:
        raise ValueError(err)
    lines = mid.splitlines()
    data = _rows_index([l.strip().strip("|").split("|") for l in lines
                        if l.strip().startswith("|")])
    if not data:
        raise ValueError("no data rows")
    idx = [i for i, l in enumerate(lines) if l.strip().startswith("|")][data[0]]
    cells = [c.strip() for c in lines[idx].strip().strip("|").split("|")]
    fenced = "| " + " | ".join(cells) + " |"
    cells[2] = "non-zero"
    lines[idx] = "| " + " | ".join(cells) + " |"
    out = "\n```\n" + fenced + "\n```\n" + "\n".join(lines) + "\n"
    return skill.replace(mid, out, 1)


def m_no_header(skill, spec):
    mid, err = split_section(skill, spec)
    if err:
        raise ValueError(err)
    lines = mid.splitlines()
    hdr = next((i for i, l in enumerate(lines)
                if l.strip().startswith("|") and not is_sep(
                    [c.strip() for c in l.strip().strip("|").split("|")])), None)
    if hdr is None:
        raise ValueError("no header row")
    lines[hdr] = "| tool | purpose | exit map |"
    return skill.replace(mid, "\n".join(lines) + "\n", 1)


MUTATIONS = [("fenced", "skill", m_fenced), ("off-section", "skill", m_off_section),
             ("substring-cell", "skill", m_substring_cell),
             ("prose-exit", "skill", m_prose_exit),
             ("html-comment", "skill", m_html_comment),
             ("first-wins-shadow", "skill", m_thin_shadow),
             ("no-header", "skill", m_no_header)]


def run_battery(root, rev, spec_name, scratch_root):
    spec = SPECS[spec_name]
    skill = gate.show(root, rev, "SKILL.md")
    if skill is None:
        return {"error": "SKILL.md absent at rev"}
    files = lambda p: gate.show(root, rev, p)  # noqa: E731
    scope, err = load_scope(files, spec)
    if err:
        return {"error": err}
    out = {"fixtures": [], "forgeries_total": 0, "v1_green": 0, "v2_green": 0,
           "genuine_green": 0}
    code, _ = score(skill, files, spec_name, "v2", rev)
    out["genuine_green"] = 1 if code == 0 else 0
    out["genuine_exit"] = code
    need = ["SKILL.md", spec["census"]] + scope
    for name, _, fn in MUTATIONS:
        try:
            text = fn(skill, spec) if name != "fenced" else skill.replace(
                split_section(skill, spec)[0], m_fenced(split_section(skill, spec)[0]), 1)
        except (ValueError, TypeError) as exc:
            out["fixtures"].append({"name": name, "error": str(exc)})
            out["forgeries_total"] += 1
            continue
        if text == skill:
            out["fixtures"].append({"name": name, "error": "mutation was a no-op"})
            out["forgeries_total"] += 1
            out["v2_green"] += 1
            continue
        d = tempfile.mkdtemp(dir=scratch_root, prefix="fx-")
        try:
            subprocess.run(["git", "-C", d, "init", "-q"], check=True)
            for k, v in (("user.email", "fx@round46"), ("user.name", "round46 fixture")):
                subprocess.run(["git", "-C", d, "config", k, v], check=True)
            for p in need:
                body = gate.show(root, rev, p)
                if body is None:
                    continue
                full = os.path.join(d, p)
                os.makedirs(os.path.dirname(full), exist_ok=True)
                with open(full, "w") as fh:
                    fh.write(body)
            with open(os.path.join(d, "SKILL.md"), "w") as fh:
                fh.write(text)
            subprocess.run(["git", "-C", d, "add", "-A"], check=True)
            subprocess.run(["git", "-C", d, "commit", "-q", "-m", "fixture"], check=True)
            frev = subprocess.run(["git", "-C", d, "rev-parse", "HEAD"],
                                  capture_output=True, text=True).stdout.strip()
            f = lambda p, d=d: gate.show(d, frev, p)  # noqa: E731
            c1, _ = score(text, f, spec_name, "v1", frev)
            c2, r2 = score(text, f, spec_name, "v2", frev)
        finally:
            shutil.rmtree(d, ignore_errors=True)
        out["forgeries_total"] += 1
        out["v1_green"] += 1 if c1 == 0 else 0
        out["v2_green"] += 1 if c2 == 0 else 0
        out["fixtures"].append({"name": name, "v1_exit": c1, "v2_exit": c2,
                                "v2_failing": r2.get("failing", r2.get("reason"))})
    return out


