#!/usr/bin/env python3
"""R46-C2 counter: the instrument registry, scored by a discriminating check.

Frozen target (`plans/round-46-claims.md`, R46-C2).  The scope is the census at
`tools/round-46/census.json`, generated by `census.py` from what the round-41..46
claim files name — never a hand-kept list, and never a number assumed in code.

  registered          every census path is the exact first cell of a registry row
  unregistered        == []
  thin                == []   the verdict-map cell enumerates `0=`, `1=`, `2=`
  absent_at_rev       == []   every registered path exists at `--rev` (R45-CL2)
  forged_accepted     == 0    none of the 7 forgery classes registers

The section is bound by `<!-- instrument-registry v2 -->` … `<!-- /instrument-registry -->`
and nothing outside it, inside a fenced block or inside an HTML comment registers
(R45-CL14 a/c).  Cell 0 is exact equality against the backticked path, not a
substring search (R45-CL14 b), and the header row must be exact (R45-CL14 d).

`--profile v1` is the round-45 clause set ported so the same forgery battery can be
scored both ways; `--spec r45 --profile v1` reproduces the round-45 verdict on the
round-45 artefact (fidelity).

Exit codes: 0 met; 1 not met; 2 could-not-evaluate.
"""
import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gate  # noqa: E402

SELF = "tools/round-46/registry.py"
CENSUS = "tools/round-46/census.json"
HEAD = "<!-- instrument-registry v2 -->"
TAIL = "<!-- /instrument-registry -->"
HOUSE = ["tool", "gate or probe - purpose", "verdict map (exit codes)",
         "self-test command", "pinned-value path", "write scope", "owner"]
PATHCELL = re.compile(r"`(tools/[A-Za-z0-9._/-]+\.(?:py|sh))`")
# A verdict map binds each code to a meaning; prose that merely mentions the
# digits ("0 rows, 1 column, 2 bytes") binds nothing (R45-CL14 d).
EXITMAP = re.compile(r"\b([012])\s*[=:]")

SPECS = {
    "r46": {"census": CENSUS, "markers": (HEAD, TAIL), "house": HOUSE,
            "scope_size": None, "strict_cell": True, "strict_header": True,
            "strict_exit": True, "presence": True,
            "claims": "plans/round-46-claims.md"},
    "r45": {"census": "tools/round-45/registry-scope.json", "markers": None,
            "house": ["tool"], "scope_size": 6, "strict_cell": False,
            "strict_header": False, "strict_exit": False, "presence": False,
            "claims": "plans/round-45-claims.md"},
}


def rows_anywhere(skill):
    """Round-45 parse: any table row in the file, fence- and comment-blind."""
    out = []
    for line in skill.splitlines():
        s = line.strip()
        if not s.startswith("|"):
            continue
        cells = [c.strip() for c in s.strip("|").split("|")]
        # Round-45 `parse_rows` looked at cell 0 only; the port keeps that.
        if cells and PATHCELL.search(cells[0]):
            out.append(cells)
    return out


def split_section(skill, spec):
    head, tail = spec["markers"]
    if skill.count(head) != 1 or skill.count(tail) != 1:
        return None, f"markers: {skill.count(head)} open, {skill.count(tail)} close"
    i = skill.index(head) + len(head)
    j = skill.index(tail)
    if j < i:
        return None, "close marker precedes open marker"
    return skill[i:j], None


def rows_in_section(mid):
    """Fence-aware and HTML-comment-aware parse of the bound section."""
    out, fence, comment = [], False, False
    for line in mid.splitlines():
        s = line.strip()
        if s.startswith("```") or s.startswith("~~~"):
            fence = not fence
            continue
        if fence:
            continue
        if comment:
            if "-->" in s:
                comment = False
            continue
        if s.startswith("<!--"):
            if "-->" not in s:
                comment = True
            continue
        if not s.startswith("|"):
            continue
        out.append([c.strip() for c in s.strip("|").split("|")])
    return out


def is_sep(cells):
    return all(c == "" or re.fullmatch(r":?-{2,}:?", c) for c in cells)


def grid(lines):
    header, rows = None, []
    for cells in lines:
        if is_sep(cells):
            continue
        if header is None:
            header = cells
        else:
            rows.append(cells)
    return header, rows


def load_scope(files, spec):
    body = files(spec["census"])
    if body is None:
        return None, f"scope file absent at rev: {spec['census']}"
    try:
        doc = json.loads(body)
    except ValueError as exc:
        return None, f"scope unreadable: {exc}"
    paths = doc.get("paths") if isinstance(doc, dict) else doc
    if not isinstance(paths, list) or not paths:
        return None, "scope lists no path"
    return list(dict.fromkeys(paths)), None


def score(skill, files, spec_name, profile, rev, battery=None):
    spec = SPECS[spec_name]
    hard = profile == "v2"
    scope, err = load_scope(files, spec)
    receipt = {"counter": "round-46-c2", "profile": profile, "spec": spec_name, "rev": rev}
    if err:
        return 2, dict(receipt, reason=err)
    failing = []
    if spec["markers"] and hard:
        mid, err = split_section(skill, spec)
        if err:
            # The bound section is part of the predicate, not of evaluability: its
            # absence is a not-met clause, and nothing outside it may register.
            failing.append(err)
            mid = ""
        cells = rows_in_section(mid)
    elif spec["markers"]:
        mid, err = split_section(skill, spec)
        if err:
            mid = ""
        cells = rows_anywhere(skill)
    else:
        cells = rows_anywhere(skill)
    header, rows = grid(cells)
    if not hard:
        # Round-45 parse fidelity: every table line is a candidate row; there is no
        # header concept, so a fenced "good" row can shadow an honest thin one.
        rows, header = cells, None
    receipt.update({"scope_size": len(scope), "registry_rows": len(rows),
                    "header": header})
    if hard and spec["strict_header"]:
        if header != spec["house"]:
            failing.append(f"header != house schema ({len(spec['house'])} cells)")
    if spec["scope_size"] is not None and len(scope) != spec["scope_size"]:
        failing.append(f"scope_size {len(scope)} != {spec['scope_size']}")

    by_path = {}
    for row in rows:
        if not row:
            continue
        if hard and spec["strict_cell"]:
            key = row[0].strip()
            if key.startswith("`") and key.endswith("`") and len(key) > 2:
                by_path.setdefault(key[1:-1], row)
        else:
            m = PATHCELL.search(row[0]) if row else None
            if m:
                by_path.setdefault(m.group(1), row)
    registered, unregistered, thin = [], [], []
    for path in scope:
        row = by_path.get(path)
        if row is None:
            unregistered.append(path)
            continue
        registered.append(path)
        if hard and spec["strict_exit"]:
            cell = row[2] if len(row) > 2 else ""
            keys = set(EXITMAP.findall(cell))
            if keys != {"0", "1", "2"}:
                thin.append(path)
        else:
            cell = row[2] if len(row) > 2 else ""
            if not all(re.search(r"\b%d\b" % d, cell) for d in (0, 1, 2)):
                thin.append(path)
    absent = []
    if hard and spec["presence"]:
        absent = [p for p in registered if files(p) is None]
    if unregistered:
        failing.append(f"unregistered: {len(unregistered)} of {len(scope)}")
    if thin:
        failing.append(f"thin verdict-map cells: {len(thin)}")
    if absent:
        failing.append(f"registered but absent at rev: {absent}")
    receipt.update({"registered": registered, "unregistered": unregistered,
                    "thin": thin, "absent_at_rev": absent})
    if battery is not None:
        receipt["battery"] = battery
        for key, want in (("forgeries_total", 7), ("v1_green", 7), ("v2_green", 0),
                          ("genuine_green", 1)):
            if battery.get(key) != want:
                failing.append(f"battery {key} {battery.get(key)} != {want}")
    receipt["met_target"] = not failing
    receipt["failing"] = failing
    return (0 if not failing else 1), receipt


