SCOPE6 = ["tools/round-44/a.py", "tools/round-44/b.sh", "tools/round-44/c.py",
          "tools/round-45/x.py", "tools/round-45/y.py", "tools/round-45/z.py"]


def house_row(path, exits="0=met; 1=not met; 2=could-not-evaluate"):
    return (f"| `{path}` | gate | {exits} | `--selftest` | none | repo | kaidoku |")


def registry_text(paths, header=" | ".join(HOUSE), wrap=True):
    body = "| " + header + " |\n|" + "---|" * len(HOUSE) + "\n"
    body += "\n".join(house_row(p) for p in paths) + "\n"
    if not wrap:
        return body
    return ("\n### Round-46 instrument registry\n\n" + HEAD + "\n\n" + body + "\n" + TAIL + "\n")


def census_doc(paths):
    return json.dumps({"rule": "census.py: every tools/round-4[1-6]/**.{py,sh} named by "
                               "plans/round-4[1-6]-claims.md", "paths": paths}, indent=1)


def selftest():
    root, err = gate.scratch("kaidoku-r46-registry-selftest-")
    if err:
        print(json.dumps({"reason": err}))
        return 2
    cases = []

    def mk(skill, scope, files_present):
        d = tempfile.mkdtemp(dir=root, prefix="self-")
        subprocess.run(["git", "-C", d, "init", "-q"], check=True)
        for k, v in (("user.email", "st@round46"), ("user.name", "round46 selftest")):
            subprocess.run(["git", "-C", d, "config", k, v], check=True)
        files = {"SKILL.md": skill, CENSUS: census_doc(scope),
                 "plans/round-46-claims.md": "# claims\n\n## Frozen paths (exact)\n\n"
                 "- `plans/round-46-claims.md`\n- `tools/round-46/`\n"}
        for p in files_present:
            files[p] = "#!/usr/bin/env python3\n"
        for path, text in files.items():
            full = os.path.join(d, path)
            os.makedirs(os.path.dirname(full), exist_ok=True)
            with open(full, "w") as fh:
                fh.write(text)
        subprocess.run(["git", "-C", d, "add", "-A"], check=True)
        subprocess.run(["git", "-C", d, "commit", "-q", "-m", "fixture"], check=True)
        rev = subprocess.run(["git", "-C", d, "rev-parse", "HEAD"],
                             capture_output=True, text=True).stdout.strip()
        return d, rev

    def case(name, expect, skill, scope=None, files_present=None, profile="v2"):
        scope = scope or ["tools/round-46/a.py", "tools/round-46/b.py"]
        files_present = scope if files_present is None else files_present
        d = None
        try:
            d, rev = mk(skill, scope, files_present)
            code, rec = evaluate(d, rev, rev, "r46", profile, with_battery=False)
        except Exception as exc:  # noqa: BLE001
            code, rec = "crash", {"error": f"{type(exc).__name__}: {exc}"}
        finally:
            if d:
                shutil.rmtree(d, ignore_errors=True)
        cases.append({"case": name, "expect": expect, "got": code, "ok": code == expect,
                      "failing": rec.get("failing") or rec.get("reason") or rec.get("error")})

    two = ["tools/round-46/a.py", "tools/round-46/b.py"]
    rows = "\n".join(house_row(p) for p in two)
    case("green", 0, registry_text(two))
    case("red-unregistered", 1, registry_text(two[:1]))
    case("red-thin-exit", 1, registry_text(two).replace(
        "0=met; 1=not met; 2=could-not-evaluate", "non-zero on failure", 1))
    case("red-prose-exit", 1, registry_text(two).replace(
        "0=met; 1=not met; 2=could-not-evaluate", "0 rows, 1 column, 2 bytes", 1))
    case("red-absent-at-rev", 1, registry_text(two + ["tools/round-46/ghost.py"]),
         scope=two + ["tools/round-46/ghost.py"], files_present=two)
    case("red-fenced", 1, "\n### R\n\n" + HEAD + "\n\n```\n" + rows + "\n```\n" + TAIL + "\n")
    case("red-html-comment", 1, "\n### R\n\n" + HEAD + "\n\n<!--\n" + rows + "\n-->\n" + TAIL + "\n")
    case("red-no-markers", 1, registry_text(two, wrap=False))
    case("red-header-not-house", 1,
         registry_text(two, header="tool | purpose | exit map | a | b | c | d"))
    case("red-outside-section", 1, "\n### R\n\n" + rows + "\n\n" + HEAD + "\n" + TAIL + "\n")
    case("red-substring-cell", 1,
         registry_text(two).replace(f"| `{two[0]}` |", f"| see `{two[0]}` (wrapper) |"))
    case("red-v1-accepts-fenced", 0,
         "\n### R\n\n" + HEAD + "\n\n```\n" + rows + "\n```\n" + TAIL + "\n", profile="v1")

    failures = [c for c in cases if not c["ok"]]
    print("REGISTRY_SELFTEST: cases=%d failures=%d" % (len(cases), len(failures)))
    print(json.dumps({"cases": cases, "failures": len(failures)}, indent=1))
    shutil.rmtree(root, ignore_errors=True)
    return 0 if not failures else 1


if __name__ == "__main__":
    sys.exit(main())
