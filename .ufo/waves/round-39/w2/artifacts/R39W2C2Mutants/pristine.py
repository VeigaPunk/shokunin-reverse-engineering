def selftest():
    SAME = object()
    ABSENT = object()
    sroot = os.path.join(os.environ.get('HYAKU_SCRATCH') or os.path.join(tempfile.gettempdir(), 'hyaku'),
                         'kaidoku-r39')
    os.makedirs(sroot, exist_ok=True)
    fails = []

    def row(label, pat):
        return ['`%s`' % label, '`%s`' % pat, '`*`', '`*`', '`*`', '`*`', '`*`', 'reason', '`corpus/k.md:1-1`']

    GREEN_TABLE = [row('clean', 'clean'), row('dep-missing-be', 'dep-missing-be')]
    CATCH_ALL = [row('clean', '*')]
    PARTIAL = [row('clean', 'clean')]

    def table_text(rows):
        sep = '|' + '---|' * len(HEADER)
        return '\n'.join(['| ' + ' | '.join(HEADER) + ' |', sep] +
                         ['| ' + ' | '.join(r) + ' |' for r in rows])

    def skill_doc(rows):
        s = '# K\n\n## Queue-drain craft (x)\n\n- **rule** text\n\n'
        if rows is not None:
            s += '<!-- sqfs-triage-table v1 -->\n\n' + table_text(rows) + '\n\n'
        return s + '## Next\n\n- other\n'

    def write_tree(d, tree):
        for p, c in tree.items():
            fp = os.path.join(d, p)
            os.makedirs(os.path.dirname(fp) or d, exist_ok=True)
            with open(fp, 'wb') as f:
                f.write(c if isinstance(c, bytes) else c.encode())

    def commit(d, tree, msg='x'):
        write_tree(d, tree)
        subprocess.run(['git', '-C', d, 'add', '-A'], check=True)
        subprocess.run(['git', '-C', d, '-c', 'user.name=fx', '-c', 'user.email=fx@fx',
                        'commit', '-qm', msg, '--allow-empty'], check=True)
        return subprocess.run(['git', '-C', d, 'rev-parse', 'HEAD'],
                              capture_output=True, text=True).stdout.strip()

    def build(params):
        d = tempfile.mkdtemp(prefix='c2-case.', dir=sroot)
        subprocess.run(['git', '-C', d, 'init', '-q'], check=True)
        top = subprocess.run(['git', '-C', d, 'rev-parse', '--show-toplevel'],
                             capture_output=True, text=True).stdout.strip()
        if os.path.realpath(top) != os.path.realpath(d):
            raise SystemExit('fixture toplevel mismatch')
        commit(d, {'SKILL.md': skill_doc(None)}, 'base')
        fr_rows = params.get('table_freeze', GREEN_TABLE)
        tool_tree = {
            SKILL: skill_doc(None if fr_rows is ABSENT else fr_rows),
            'tools/round-39/sqfs-triage.py': STUB_INTERP,
            'tools/round-39/heldout-gen.py': STUB_GEN,
            'tools/round-39/c2-counter.py': '# counter\n',
            'plans/round-39-claims.md': '# claims\n',
        }
        claim = params.get('claim', 'after')
        muts = params.get('muts', set())
        if params.get('seed') == 'zero':
            seed = '0' * 64
        # claim data is built after the freeze hash exists
        freeze = commit(d, tool_tree, 'freeze')
        if claim == 'none':
            return d, freeze, freeze
        seed = '0' * 64 if params.get('seed') == 'zero' else freeze
        gdir = tempfile.mkdtemp(prefix='gen.', dir=sroot)
        gen_path = os.path.join(d, GEN)
        pr = subprocess.run([sys.executable, '-I', '-B', gen_path, '--seed', seed, '--out', gdir],
                            capture_output=True, text=True)
        if pr.returncode != 0:
            raise SystemExit('stub generator failed: ' + pr.stderr)
        rman = json.load(open(os.path.join(gdir, 'manifest.json')))
        man = {'seed': seed, 'generator': GEN, 'classes': rman['classes'], 'carriers': []}
        if params.get('gen_obj'):
            man['generator'] = {
                'name': 'heldout-gen.py', 'version': 'r39-c2-v1',
                'sha256': hashlib.sha256(STUB_GEN.encode()).hexdigest()
                if params.get('gen_obj') == 'good' else 'f' * 64,
                'carriers_per_class': 2}
        claim_files = {}
        for c in rman['carriers']:
            cid = c['id']
            body = open(os.path.join(gdir, cid, 'carrier.sqsh'), 'rb').read()
            if 'carrier_corrupt' in muts and cid == 'H01':
                body += b'X'
            base = 'corpus/evidence/round-39/c2/heldout/' + cid
            claim_files[base + '/carrier.sqsh'] = body
            env = {'subject': {'name': 'carrier.sqsh',
                               'digest': {'sha256': '0' * 64 if ('digest_mismatch' in muts and cid == 'H01')
                                          else c['sha256']},
                               'format': 'file', 'architecture': None, 'local_path': '/fast/scratch/x'},
                   'operation': 'analyze' if ('envelope_op' in muts and cid == 'H03') else 'extract_firmware',
                   'provider': {'id': 'unblob'},
                   'normalized_result': {'extraction_gaps': [], 'files': [], 'chunks': [], 'diagnostics': []},
                   'stub_class': c.get('label', c['class'])}
            if 'missing_envelope' in muts and cid == 'H02':
                pass
            else:
                blob = {'ok': True, 'data': env, 'meta': {'cli': 'rea-agents@6.5.0'}} \
                    if 'full_envelope' in muts else env
                claim_files[base + '/envelope.json'] = json.dumps(blob, indent=1, sort_keys=True)
            entry = dict(c)
            if 'lane_relative_paths' in muts:
                entry['carrier'] = base + '/carrier.sqsh'
            if 'omit_envelope' not in muts:
                entry['envelope'] = (base + '/envelope.json') if 'lane_relative_paths' in muts \
                    else (cid + '/envelope.json')
            if 'mislabel' in muts and cid == 'H01':
                entry['label'] = 'dep-missing-be'
            if 'share_carrier_path' in muts and cid == 'H02':
                entry['carrier'] = 'H01/carrier.sqsh'
            man['carriers'].append(entry)
        if 'class_count3' in muts:
            body = claim_files['corpus/evidence/round-39/c2/heldout/H01/carrier.sqsh']
            claim_files['corpus/evidence/round-39/c2/heldout/H07/carrier.sqsh'] = body
            claim_files['corpus/evidence/round-39/c2/heldout/H07/envelope.json'] = \
                claim_files['corpus/evidence/round-39/c2/heldout/H01/envelope.json']
            man['carriers'].append({'id': 'H07', 'class': 'clean-be', 'label': 'clean',
                                    'arm': 'after', 'carrier': 'H07/carrier.sqsh',
                                    'sha256': hashlib.sha256(body).hexdigest(),
                                    'envelope': 'H07/envelope.json'})
        man_text = json.dumps(man, indent=1, sort_keys=True)
        rev_rows = params.get('table_rev', SAME)
        if rev_rows is not SAME:
            post = {SKILL: skill_doc(None if rev_rows is ABSENT else rev_rows)}
        else:
            post = {}
        for m, p in (('edit_interp', INTERP), ('edit_gen', GEN),
                     ('edit_claims', CLAIMS), ('edit_counter', COUNTER)):
            if m in muts:
                cur = tool_tree[p]
                post[p] = cur + ('\n# edited after freeze\n' if isinstance(cur, str) else b'#x\n')
        claim_dir = MANIFEST.rsplit('/', 1)[0]
        if claim == 'after':
            tree = dict(claim_files)
            tree[MANIFEST] = man_text
            tree.update(post)
            rev = commit(d, tree, 'claim data')
        elif claim == 'split':
            rev = commit(d, dict(claim_files), 'carriers and envelopes')
            tree = {MANIFEST: man_text}
            tree.update(post)
            rev = commit(d, tree, 'manifest')
        elif claim == 'befreeze':
            # manifest added before the freeze commit: freeze moves one commit later
            d2 = d
            commit(d2, dict(claim_files), 'claim data before freeze')
            tree = {MANIFEST: man_text, 'plans/round-39-freeze.txt': 'freeze\n'}
            tree.update(post)
            rev = commit(d2, tree, 'freeze marker')
            freeze = rev
        else:
            raise SystemExit('unknown claim mode ' + claim)
        return d, freeze, rev

    cases = [
        ('green: all bindings and labels', dict(), 0, [], []),
        ('do-nothing: no manifest at rev', dict(claim='none', table_freeze=ABSENT), 2, [], []),
        ('table removed after freeze', dict(table_rev=ABSENT), 1, ['triage_table_present'], []),
        ('seed != freeze', dict(seed='zero'), 1, ['seed_matches_freeze'], []),
        ('manifest before freeze', dict(claim='befreeze'), 1,
         ['manifest_after_freeze', 'seed_matches_freeze'], []),
        ('envelope before manifest', dict(claim='split'), 1, ['manifest_before_envelopes'], []),
        ('table edited after freeze', dict(table_rev=[row('clean', 'clean'),
                                                      row('dep-missing-be', 'dep-missing-be'),
                                                      row('x', 'y')]), 1, ['triage_table_identical'], []),
        ('interpreter edited after freeze', dict(muts={'edit_interp'}), 2, [], []),
        ('generator edited after freeze', dict(muts={'edit_gen'}), 2, [], []),
        ('claims edited after freeze', dict(muts={'edit_claims'}), 2, [], []),
        ('counter edited after freeze', dict(muts={'edit_counter'}), 2, [], []),
        ('carrier not regenerable', dict(muts={'carrier_corrupt'}), 1, ['carriers_committed'], []),
        ('subject digest mismatch', dict(muts={'digest_mismatch'}), 1, ['envelopes_valid'], []),
        ('envelope operation wrong', dict(muts={'envelope_op'}), 1, ['envelopes_valid'], []),
        ('missing envelope', dict(muts={'missing_envelope'}), 1, ['envelopes_valid'], []),
        ('3 carriers in one class', dict(muts={'class_count3'}), 1,
         ['classes_two_each', 'n_equals_twice_classes'], []),
        ('one mislabel', dict(muts={'mislabel'}), 1, [], []),
        ('catch-all table', dict(table_freeze=CATCH_ALL), 1, [], []),
        ('unclassified', dict(table_freeze=PARTIAL), 1, [], []),
        ('consistency: labels right, binding false', dict(seed='zero'), 1, ['seed_matches_freeze'], []),
        ('generator object with matching sha', dict(gen_obj='good'), 0, [], []),
        ('generator object with wrong sha', dict(gen_obj='bad'), 1, ['generator_sha_matches_freeze'], []),
        ('envelope path omitted, sibling inferred', dict(muts={'omit_envelope'}), 0, [], []),
        ('two carriers share one carrier path', dict(muts={'share_carrier_path'}), 1,
         ['carrier_paths_unique'], []),
        ('full CLI envelope ok/data/meta', dict(muts={'full_envelope'}), 0, [], []),
        ('lane-root-relative carrier and envelope paths', dict(muts={'lane_relative_paths'}), 0, [], []),
    ]
    green = red = 0
    for name, params, want, want_false, want_true in cases:
        d = None
        try:
            d, freeze, rev = build(params)
            try:
                r = measure(d, rev, freeze)
                got = 0 if r['met_target'] else 1
                receip = r
            except Unevaluable as e:
                got = 2
                receip = e.receipt
            ok = got == want
            if got in (0, 1) and receip.get('met_target_consistent') is not True:
                ok = False
                fails.append('%s: met_target_consistent false' % name)
            if got in (0, 1):
                for k in want_false:
                    if receip.get('bindings', {}).get(k) is not False:
                        ok = False
                        fails.append('%s: binding %s not false (got %r)' % (name, k, receip.get('bindings', {}).get(k)))
                for k in want_true:
                    if receip.get('bindings', {}).get(k) is not True:
                        ok = False
                        fails.append('%s: binding %s not true' % (name, k))
            if ok:
                if want == 0:
                    green += 1
                else:
                    red += 1
            elif got != want:
                fails.append('%s: want exit %d got %d' % (name, want, got))
        except SystemExit as e:
            fails.append('%s: fixture error %s' % (name, e))
        finally:
            if d:
                shutil.rmtree(d, ignore_errors=True)

    # consistency detector exercised directly (not a fixture case)
    consistency_ok = True
    for matched, n, vals, met, exp in [
            (4, 4, [True, True], True, True), (3, 4, [True, True], False, True),
            (4, 4, [True, False], False, True), (4, 4, [True, False], True, False),
            (3, 4, [True, True], True, False)]:
        got = (met == bool(matched == n and all(v is True for v in vals)))
        consistency_ok = consistency_ok and got == exp
    if not consistency_ok:
        fails.append('met_target/matched consistency detector wrong')
    total = len(cases) + 1
    passed = total - len(fails)
    print(json.dumps({'selftest': 'c2-counter', 'cases': total, 'pass': passed, 'fail': len(fails),
                      'failures': fails}))
    print('SELFTEST cases=%d pass=%d fail=%d' % (total, passed, len(fails)))
    return 0 if not fails else 1


