#!/usr/bin/env python3
"""R39-C2 counter (depth: executable SquashFS extract-firmware outcome triage).

Predicate P39-C2 (frozen; the same sentence as plans/round-39-claims.md):
  At the measured revision, the frozen triage interpreter
  `tools/round-39/sqfs-triage.py`, reading only the SKILL.md craft-section
  triage table, assigns every held-out envelope the label its frozen
  generator assigned before any REA run, for all N held-out carriers (2 per
  generator class); the held-out set is generated by the frozen
  `tools/round-39/heldout-gen.py` with seed = the freeze commit hash, every
  carrier regenerates byte-identically from that seed, every envelope's
  subject digest equals its carrier, the held-out manifest is first added in
  a commit descending from the freeze and no later than its envelopes, and
  the triage table bytes at the measured revision equal those at the freeze.

Target: matched == N and every binding true.

Usage:
  c2-counter.py --root LANE --rev REV --freeze FREEZE [--json-out PATH]
  c2-counter.py --selftest
Exit: 0 target met, 1 not met, 2 unevaluable (including `frozen_path_changed`).
Reads git objects only; every object is materialised into a private scratch
directory under $HYAKU_SCRATCH/kaidoku-r39 and removed at exit.
"""
import argparse, hashlib, json, os, shutil, subprocess, sys, tempfile

MANIFEST = 'corpus/evidence/round-39/c2/heldout/manifest.json'
SKILL = 'SKILL.md'
INTERP = 'tools/round-39/sqfs-triage.py'
GEN = 'tools/round-39/heldout-gen.py'
COUNTER = 'tools/round-39/c2-counter.py'
CLAIMS = 'plans/round-39-claims.md'
FROZEN = (INTERP, GEN, COUNTER, CLAIMS)
MARKER = '<!-- sqfs-triage-table v1 -->'
CRAFT = '## Queue-drain craft'
HEADER = ['label', 'handler', 'gap kinds', 'dependencies', '-be in child argv',
          'symlink removed', 'published files', 'cause -> action', 'source']


class Unevaluable(Exception):
    def __init__(self, reason, receipt=None):
        super().__init__(reason)
        self.reason = reason
        self.receipt = receipt or {}


# ------------------------------------------------------------------ git
def show(root, rev, path):
    p = subprocess.run(['git', '-C', root, 'show', '%s:%s' % (rev, path)], capture_output=True)
    return p.stdout if p.returncode == 0 else None


def present(root, rev, path):
    return subprocess.run(['git', '-C', root, 'cat-file', '-e', '%s:%s' % (rev, path)],
                          capture_output=True).returncode == 0


def full_rev(root, rev):
    p = subprocess.run(['git', '-C', root, 'rev-parse', '--verify', '%s^{commit}' % rev],
                       capture_output=True, text=True)
    if p.returncode:
        raise Unevaluable('unknown_revision:%s' % rev)
    return p.stdout.strip()


def is_ancestor(root, a, b):
    return subprocess.run(['git', '-C', root, 'merge-base', '--is-ancestor', a, b],
                          capture_output=True).returncode == 0


def first_add(root, rev, path):
    p = subprocess.run(['git', '-C', root, 'log', '--format=%H', '--diff-filter=A', '--no-renames',
                        '--reverse', rev, '--', path], capture_output=True, text=True)
    if p.returncode:
        return None
    lines = [l for l in p.stdout.split() if l]
    return lines[0] if lines else None


def frozen_changes(root, freeze, rev):
    p = subprocess.run(['git', '-C', root, 'log', '--format=%H', '--no-renames',
                        '%s..%s' % (freeze, rev), '--', *FROZEN], capture_output=True, text=True)
    return [l for l in p.stdout.split() if l]


# ------------------------------------------------------------------ table
def table_block(text):
    """Marker line through the table's last row, inside `## Queue-drain craft`."""
    if text is None:
        return None
    lines = text.splitlines()
    start = next((i for i, l in enumerate(lines) if l.lower().startswith(CRAFT.lower())), None)
    if start is None:
        return None
    end = len(lines)
    for i in range(start + 1, len(lines)):
        if lines[i].startswith('## '):
            end = i
            break
    mi = next((i for i in range(start + 1, end) if MARKER in lines[i]), None)
    if mi is None:
        return None
    ti = next((i for i in range(mi + 1, end) if lines[i].lstrip().startswith('|')), None)
    if ti is None:
        return None
    last = ti
    for i in range(ti, end):
        if not lines[i].lstrip().startswith('|'):
            break
        last = i
    return '\n'.join(lines[mi:last + 1])


def table_header_ok(block):
    if not block:
        return False
    rows = [l for l in block.splitlines() if l.lstrip().startswith('|')]
    if len(rows) < 2:
        return False
    cells = [c.strip().strip('`').strip() for c in rows[0].strip().strip('|').split('|')]
    return cells == HEADER


# ------------------------------------------------------------------ scratch
def scratch_dir():
    base = os.environ.get('HYAKU_SCRATCH') or os.path.join(tempfile.gettempdir(), 'hyaku')
    root = os.path.join(base, 'kaidoku-r39')
    os.makedirs(root, exist_ok=True)
    return tempfile.mkdtemp(prefix='c2-counter.', dir=root)


def sha256_bytes(b):
    return hashlib.sha256(b).hexdigest()


def envelope_data(obj):
    if isinstance(obj, dict) and 'subject' not in obj and isinstance(obj.get('data'), dict):
        return obj['data']
    return obj


def subject_sha(obj):
    try:
        return str(obj['subject']['digest']['sha256']).lower()
    except Exception:
        return None


# ------------------------------------------------------------------ measure
def measure(root, rev_arg, freeze_arg):
    rev = full_rev(root, rev_arg)
    freeze = full_rev(root, freeze_arg)
    res = {'predicate': 'P39-C2', 'revision': rev, 'freeze': freeze, 'freeze_arg': freeze_arg,
           'revision_arg': rev_arg, 'manifest_path': MANIFEST, 'argv': sys.argv,
           'bindings': {}, 'bindings_false': [], 'carriers': [], 'frozen_paths_changed': []}
    if not is_ancestor(root, freeze, rev):
        raise Unevaluable('freeze_not_ancestor_of_rev', res)
    changed = frozen_changes(root, freeze, rev)
    if changed:
        res['frozen_paths_changed'] = changed
        raise Unevaluable('frozen_path_changed', res)

    man_b = show(root, rev, MANIFEST)
    if man_b is None:
        raise Unevaluable('no_manifest_at_rev', res)
    try:
        man = json.loads(man_b.decode())
    except Exception:
        raise Unevaluable('manifest_unparsable', res)
    if not isinstance(man, dict):
        raise Unevaluable('manifest_not_an_object', res)

    classes = man.get('classes') if isinstance(man.get('classes'), list) else []
    carriers = man.get('carriers') if isinstance(man.get('carriers'), list) else []
    carriers = [c for c in carriers if isinstance(c, dict)]
    N = len(carriers)
    ids = [str(c.get('id', '')) for c in carriers]
    per = {}
    for c in carriers:
        per[c.get('class')] = per.get(c.get('class'), 0) + 1
    b = res['bindings']
    b['seed_matches_freeze'] = str(man.get('seed', '')).lower() == freeze
    # The generator is either a lane-relative path string (draft manifest shape)
    # or the generator's own object {name, version, sha256, ...} (real shape).
    gen_b = show(root, freeze, GEN)
    gen_sha = sha256_bytes(gen_b) if gen_b is not None else None
    g = man.get('generator')
    declared_gen_sha = None
    if isinstance(g, dict):
        b['manifest_generator_path'] = g.get('name') == 'heldout-gen.py'
        declared_gen_sha = g.get('sha256')
        b['generator_sha_matches_freeze'] = declared_gen_sha is None or declared_gen_sha == gen_sha
    else:
        b['manifest_generator_path'] = str(g) == GEN
        b['generator_sha_matches_freeze'] = True
    res['generator'] = {'declared': g, 'declared_sha256': declared_gen_sha,
                        'freeze_sha256': gen_sha}
    b['classes_unique'] = bool(classes) and len(classes) == len(set(classes)) \
        and all(isinstance(x, str) and x for x in classes)
    b['classes_two_each'] = bool(classes) and all(per.get(k) == 2 for k in classes) and set(per) <= set(classes)
    b['n_equals_twice_classes'] = N == 2 * len(classes)
    b['ids_unique'] = bool(ids) and len(set(ids)) == len(ids) and all(ids)
    b['arms_valid'] = bool(carriers) and all(c.get('arm') in ('after', 'before') for c in carriers)

    skill_rev = show(root, rev, SKILL)
    skill_fr = show(root, freeze, SKILL)
    blk_rev = table_block(skill_rev.decode() if skill_rev is not None else None)
    blk_fr = table_block(skill_fr.decode() if skill_fr is not None else None)
    b['triage_table_present'] = blk_rev is not None
    b['triage_table_identical'] = blk_rev is not None and blk_fr is not None and blk_rev == blk_fr
    res['table'] = {'present': blk_rev is not None, 'identical': b['triage_table_identical'],
                    'header_ok': table_header_ok(blk_rev),
                    'bytes': len(blk_rev.encode()) if blk_rev is not None else 0}

    interp_b = show(root, freeze, INTERP)
    b['interpreter_present_at_freeze'] = interp_b is not None

    mdir = os.path.dirname(MANIFEST)

    def resolve(p):
        if not isinstance(p, str) or not p or p.startswith('/') or '..' in p.split('/'):
            return None
        for cand in (p, mdir.rstrip('/') + '/' + p):
            if cand.startswith('./'):
                cand = cand[2:]
            if present(root, rev, cand):
                return cand
        return None

    scratch = scratch_dir()
    try:
        # ---- regeneration from the frozen generator
        regen = {}
        if gen_b is None:
            raise Unevaluable('generator_absent_at_freeze', res)
        gdir = os.path.join(scratch, 'gen')
        os.makedirs(gdir)
        gpath = os.path.join(gdir, 'heldout-gen.py')
        open(gpath, 'wb').write(gen_b)
        # The real generator loads the round-37 image writer by path
        # (KAIDOKU_GEN_SQUASHFS, or a path relative to its own __file__, which
        # in scratch is not the lane).  Materialise the writer from git and
        # hand it over by environment so argv stays exactly the frozen
        # `--seed/--out` interface; a generator that ignores it is unaffected.
        wpath = 'tools/round-37/gen-squashfs.py'
        wb = show(root, rev, wpath)
        if wb is None:
            wb = show(root, freeze, wpath)
        wdir = os.path.join(scratch, 'writer')
        os.makedirs(wdir)
        wlocal = os.path.join(wdir, 'gen-squashfs.py')
        if wb is not None:
            open(wlocal, 'wb').write(wb)
        w_sha = sha256_bytes(wb) if wb is not None else None
        gw = g.get('writer') if isinstance(g, dict) else None
        declared_w_sha = gw.get('sha256') if isinstance(gw, dict) else None
        b['writer_matches_manifest'] = declared_w_sha is None or declared_w_sha == w_sha
        res['writer'] = {'path': wpath, 'materialised': wb is not None, 'sha256': w_sha,
                         'declared_sha256': declared_w_sha,
                         'declared_path': gw.get('path') if isinstance(gw, dict) else None}
        env = dict(os.environ)
        if wb is not None:
            env['KAIDOKU_GEN_SQUASHFS'] = wlocal
        outdir = os.path.join(scratch, 'regen')
        pr = subprocess.run([sys.executable, '-I', '-B', gpath, '--seed', freeze, '--out', outdir],
                            cwd=root, capture_output=True, text=True, timeout=1800, env=env)
        if pr.returncode != 0:
            res['generator_stderr'] = (pr.stderr or '')[-2000:]
            raise Unevaluable('generator_failed', res)
        rman_path = os.path.join(outdir, 'manifest.json')
        if not os.path.exists(rman_path):
            raise Unevaluable('generator_wrote_no_manifest', res)
        try:
            rman = json.load(open(rman_path))
        except Exception:
            raise Unevaluable('regenerated_manifest_unparsable', res)
        for rc in (rman.get('carriers') or []):
            if not isinstance(rc, dict):
                continue
            rel = rc.get('carrier')
            fp = os.path.join(outdir, rel) if isinstance(rel, str) else None
            data = open(fp, 'rb').read() if fp and os.path.isfile(fp) else None
            regen[str(rc.get('id', ''))] = {
                'sha256': sha256_bytes(data) if data is not None else None,
                'class': rc.get('class'), 'label': rc.get('label'), 'arm': rc.get('arm'),
                'carrier': rel, 'manifest_sha': rc.get('sha256')}
        b['regenerated_seed_matches_freeze'] = str(rman.get('seed', '')).lower() == freeze

        # ---- per-carrier checks
        def expected_label(c):
            lab = c.get('label')
            return lab if isinstance(lab, str) and lab else c.get('class')

        env_rows = []
        for c in carriers:
            cid = str(c.get('id', ''))
            msha = str(c.get('sha256', '')).lower()
            exp = expected_label(c)
            cpath = resolve(c.get('carrier'))
            cbytes = show(root, rev, cpath) if cpath else None
            committed_sha = sha256_bytes(cbytes) if cbytes is not None else None
            r = regen.get(cid) or {}
            regen_sha = r.get('sha256')
            regen_ok = bool(regen_sha) and regen_sha == msha and r.get('class') == c.get('class') \
                and r.get('arm') == c.get('arm') and r.get('label') == c.get('label')
            commit_ok = committed_sha is not None and committed_sha == msha
            epath = c.get('envelope')
            inferred = False
            if not isinstance(epath, str) or not epath:
                # The frozen generator writes the envelope beside its carrier;
                # accept that sibling when the manifest omits the field.
                car = c.get('carrier')
                if isinstance(car, str) and '/' in car:
                    epath = car.rsplit('/', 1)[0] + '/envelope.json'
                    inferred = True
                else:
                    epath = None
            epath = resolve(epath) if epath else None
            ebytes = show(root, rev, epath) if epath else None
            digest_ok = op_ok = False
            if ebytes is not None:
                try:
                    eo = envelope_data(json.loads(ebytes.decode()))
                    digest_ok = subject_sha(eo) == msha and bool(msha)
                    op_ok = eo.get('operation') == 'extract_firmware'
                    env_rows.append({'id': cid, 'path': epath, 'bytes': ebytes})
                except Exception:
                    digest_ok = op_ok = False
            res['carriers'].append({
                'id': cid, 'class': c.get('class'), 'label': c.get('label'),
                '_carrier_path': cpath,
                'expected_label': exp, 'arm': c.get('arm'),
                'manifest_sha256': msha, 'committed_sha256': committed_sha,
                'regenerated_sha256': regen_sha, 'regen_ok': regen_ok, 'commit_ok': commit_ok,
                'envelope': epath, 'envelope_inferred': inferred,
                'digest_ok': digest_ok, 'operation_ok': op_ok})
        cp = [r.get('_carrier_path') for r in res['carriers']]
        ep = [r.get('envelope') for r in res['carriers']]
        b['carrier_paths_unique'] = N > 0 and all(cp) and len(set(cp)) == len(cp)
        b['envelope_paths_unique'] = N > 0 and all(ep) and len(set(ep)) == len(ep)
        for r in res['carriers']:
            r.pop('_carrier_path', None)
        b['carriers_regenerated'] = N > 0 and all(r['regen_ok'] for r in res['carriers'])
        b['carriers_committed'] = N > 0 and all(r['commit_ok'] for r in res['carriers'])
        b['envelopes_valid'] = N > 0 and all(r['digest_ok'] and r['operation_ok'] for r in res['carriers'])

        # ---- first-add ordering
        ma = first_add(root, rev, MANIFEST)
        b['manifest_after_freeze'] = bool(ma) and ma != freeze and is_ancestor(root, freeze, ma)
        env_firsts = []
        for row in res['carriers']:
            fa = first_add(root, rev, row['envelope']) if row['envelope'] else None
            row['envelope_first_add'] = fa
            env_firsts.append(fa)
        b['manifest_before_envelopes'] = bool(ma) and bool(env_firsts) and all(
            fa is not None and is_ancestor(root, ma, fa) for fa in env_firsts)
        res['manifest_first_add'] = ma

        # ---- labels from the frozen interpreter on SKILL.md at REV
        labels = {}
        if blk_rev is not None and interp_b is not None:
            idir = os.path.join(scratch, 'triage')
            os.makedirs(idir)
            ipath = os.path.join(idir, 'sqfs-triage.py')
            open(ipath, 'wb').write(interp_b)
            spath = os.path.join(idir, 'SKILL.md')
            open(spath, 'wb').write(skill_rev)
            edir = os.path.join(idir, 'env')
            os.makedirs(edir)
            argmap = {}
            for row in env_rows:
                p = os.path.join(edir, row['id'] + '.json')
                open(p, 'wb').write(row['bytes'])
                argmap[os.path.normpath(p)] = row['id']
            pr = subprocess.run([sys.executable, '-I', '-B', ipath, '--skill', spath] + sorted(argmap),
                                cwd=idir, capture_output=True, text=True, timeout=900)
            res['interpreter_exit'] = pr.returncode
            res['interpreter_stderr_tail'] = (pr.stderr or '')[-1000:]
            if pr.returncode != 0:
                raise Unevaluable('interpreter_failed', res)
            for line in (pr.stdout or '').splitlines():
                if '\t' not in line:
                    continue
                p, lab = line.rsplit('\t', 1)
                cid = argmap.get(os.path.normpath(p.strip()))
                if cid:
                    labels[cid] = lab.strip()
        for row in res['carriers']:
            row['label'] = labels.get(row['id'])
            row['class_match'] = row['label'] is not None and row['label'] == row['expected_label']
        matched = sum(1 for row in res['carriers'] if row['class_match'])

        # ---- target
        bindings_ok = all(v is True for v in b.values())
        met = bool(matched == N and bindings_ok)
        recomputed = bool(matched == N and all(v is True for k, v in b.items()))
        consistent = met == recomputed
        res.update({'n': N, 'matched': matched, 'bindings_ok': bindings_ok,
                    'bindings_false': sorted(k for k, v in b.items() if v is not True),
                    'met_target': met, 'met_target_formula': {'matched_equals_n': matched == N,
                                                              'all_bindings_true': bindings_ok},
                    'met_target_consistent': consistent})
        if not consistent:
            raise Unevaluable('met_target_inconsistent', res)
        return res
    finally:
        shutil.rmtree(scratch, ignore_errors=True)


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--root')
    ap.add_argument('--rev')
    ap.add_argument('--freeze')
    ap.add_argument('--json-out')
    ap.add_argument('--selftest', action='store_true')
    a = ap.parse_args(argv)
    if a.selftest:
        return selftest()
    if not (a.root and a.rev and a.freeze):
        print('usage: --root --rev --freeze required (or --selftest)', file=sys.stderr)
        return 2
    try:
        res = measure(a.root, a.rev, a.freeze)
    except Unevaluable as e:
        out = dict(e.receipt)
        out['unevaluable'] = e.reason
        out['argv'] = sys.argv
        print(json.dumps({'unevaluable': e.reason, 'revision': out.get('revision'),
                          'freeze': out.get('freeze'),
                          'frozen_paths_changed': out.get('frozen_paths_changed', [])}, sort_keys=True))
        if a.json_out:
            with open(a.json_out, 'w') as f:
                json.dump(out, f, indent=1, sort_keys=True)
        return 2
    print(json.dumps({'revision': res['revision'], 'freeze': res['freeze'], 'n': res['n'],
                      'matched': res['matched'], 'bindings_false': res['bindings_false'],
                      'met_target': res['met_target'],
                      'met_target_consistent': res['met_target_consistent']}, sort_keys=True))
    if a.json_out:
        with open(a.json_out, 'w') as f:
            json.dump(res, f, indent=1, sort_keys=True)
    return 0 if res['met_target'] else 1


