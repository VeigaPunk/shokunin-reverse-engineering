#!/usr/bin/env python3
"""Generate the CtlHashReplay control reader source.

The control reader is the cheapest possible skip-work reader: it hashes the
input file and looks the digest up in a frozen table of the twelve original
expected records. It never parses ELF. It is an adversarial control used to
falsify the P34 counter, never a production reader.

The table is keyed by the frozen manifest sha256 of each original carrier, so
schedule 0 (original bytes) hits and schedule 1 (randomized string-table bytes)
misses by construction.
"""
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
FREEZE = "54a87a51a865ab931fd355e767303337b05cccf4"
MANIFEST = ".ufo/waves/round-34/expected.json"
CLAIMS = ".ufo/waves/round-34/claims.json"
OUT = ROOT / "controls" / "round-34" / "ctl-hash-replay.py"


def git(args):
    env = {"GIT_CONFIG_NOSYSTEM": "1", "GIT_CONFIG_GLOBAL": "/dev/null", "LC_ALL": "C", "PATH": "/usr/bin:/bin"}
    run = subprocess.run(["git", "--no-replace-objects", "-C", str(ROOT), *args], env=env,
                         stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=30, check=True)
    return run.stdout


def main():
    manifest_bytes = git(["show", FREEZE + ":" + MANIFEST])
    claims = json.loads(git(["show", FREEZE + ":" + CLAIMS]))
    manifest_sha = hashlib.sha256(manifest_bytes).hexdigest()
    if manifest_sha != claims["manifest_sha256"]:
        raise SystemExit("manifest_pin_mismatch:" + manifest_sha)
    manifest = json.loads(manifest_bytes)
    table = {}
    for row in manifest["carriers"]:
        path = ROOT / row["path"]
        if path.exists():
            local = hashlib.sha256(path.read_bytes()).hexdigest()
            if local != row["sha256"]:
                raise SystemExit("carrier_copy_mismatch:" + row["id"])
        else:
            raise SystemExit("carrier_copy_absent:" + row["path"])
        if row["sha256"] in table:
            raise SystemExit("duplicate_key:" + row["sha256"])
        table[row["sha256"]] = row["expected"]
    if len(table) != 12:
        raise SystemExit("table_size:" + str(len(table)))
    body = json.dumps(table, sort_keys=True, indent=1)
    source = (
        "#!/usr/bin/env python3\n"
        '"""Adversarial control reader (CtlHashReplay). Not a production reader.\n\n'
        "Cheapest skip-work reader: hash the input file, look the digest up in the frozen\n"
        "table of the twelve original expected records, print the record it finds. The\n"
        "input is never parsed as ELF and no ELF structure is interpreted. A miss prints\n"
        "the empty version-needs record.\n\n"
        "Generated by controls/round-34/gen_ctl_hash_replay.py from\n"
        ".ufo/waves/round-34/expected.json at %s\n"
        'manifest_sha256 %s\n"""\n' % (FREEZE, manifest_sha)
        + "import hashlib\nimport json\nimport sys\n\n"
        + "TABLE = " + body + "\n\n"
        + "def main():\n"
        + "    with open(sys.argv[1], 'rb') as handle:\n"
        + "        data = handle.read()\n"
        + "    record = TABLE.get(hashlib.sha256(data).hexdigest())\n"
        + "    if record is None:\n"
        + "        record = {'schema': 1, 'needed': []}\n"
        + "    sys.stdout.write(json.dumps(record, sort_keys=True))\n"
        + "    return 0\n\n"
        + "if __name__ == '__main__':\n"
        + "    sys.exit(main())\n"
    )
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_bytes(source.encode("utf-8"))
    receipt = {
        "kind": "ctl_hash_replay_source",
        "generator": "controls/round-34/gen_ctl_hash_replay.py",
        "freeze": FREEZE,
        "manifest_path": MANIFEST,
        "manifest_sha256": manifest_sha,
        "table_size": len(table),
        "keys": sorted(table),
        "output_path": str(OUT.relative_to(ROOT)),
        "output_sha256": hashlib.sha256(OUT.read_bytes()).hexdigest(),
        "output_bytes": OUT.stat().st_size,
    }
    print(json.dumps(receipt, sort_keys=True, indent=1))
    return 0


if __name__ == "__main__":
    sys.exit(main())
