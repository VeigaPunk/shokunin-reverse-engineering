#!/usr/bin/env python3
"""EX-25 (c3, arc3-loop1-round4) attack battery against a given tool revision.

Usage: attacks.py <phase>            # phase = before | candidate | after

Every attack is a single command whose exit/stdout are captured verbatim into
out/<phase>/attacks.out.  Fixtures live under fixtures/ and are generated by
harness/build-fixtures.py (tool-rendered stanzas + synthetic padding) plus the
hardlink/spelling vectors built here.

Custody paths are read-only; scratch under /var/tmp/ex25-r4 only.
"""
from __future__ import annotations

import hashlib
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path("/var/tmp/ex25-r4")
FIX = ROOT / "fixtures"


def sha256_file(p: Path) -> str:
    h = hashlib.sha256()
    with p.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 16), b""):
            h.update(chunk)
    return h.hexdigest()


def build_hardlink_fixture() -> Path:
    """Pinned fixture built by harness/build-fixtures2.py — consumed read-only here
    so the bytes are identical across phases."""
    out = FIX / "hardlink5-pre.txt"
    assert out.exists(), "run harness/build-fixtures2.py first"
    return out


def build_drifted_fixture() -> Path:
    out = FIX / "dupe5-onepath-drifted-pre.txt"
    if not out.exists():
        src = (FIX / "dupe5-one-path-pre.txt").read_text(encoding="utf-8")
        t = src.replace("16f496e663d0c91252d17dcb8094d141a8feb713466e2fb4f14267bf744263a4", "0" * 64)
        out.write_text(t, encoding="utf-8")
    return out


def main() -> int:
    phase = sys.argv[1]
    tool = ROOT / "tools" / phase / "custody-pair.py"
    outdir = ROOT / "out" / phase
    outdir.mkdir(parents=True, exist_ok=True)
    tool_sha = sha256_file(tool)

    hl = build_hardlink_fixture()
    drifted = build_drifted_fixture()

    attacks = [
        ("A1-hardlink-5-names-1-inode-req5",
         ["verify", hl, "--live", "--require-paths", "5"]),
        ("A2-hardlink-5-names-1-inode-noflag",
         ["verify", hl, "--live"]),
        ("A3-spelling-5x-one-path-req5",
         ["verify", FIX / "spelling5-one-path-pre.txt", "--live", "--require-paths", "5"]),
        ("A4-dupe-with-unevaluable-copy-req5",
         ["verify", FIX / "dupe5-unevaluable-pre.txt", "--live", "--require-paths", "5"]),
        ("A5-four-custody-plus-extra-req5",
         ["verify", FIX / "four-custody-plus-extra-pre.txt", "--live", "--require-paths", "5"]),
        ("A6-drifted-padded-req5-fail-closed",
         ["verify", drifted, "--live", "--require-paths", "5"]),
        ("A7-drifted-padded-noflag",
         ["verify", drifted, "--live"]),
        ("A8-req0-boundary",
         ["verify", FIX / "dupe5-one-path-pre.txt", "--live", "--require-paths", "0"]),
        ("A9-req-negative-boundary",
         ["verify", FIX / "dupe5-one-path-pre.txt", "--live", "--require-paths", "-1"]),
        ("A10-dupe4plus1-req4-passes",
         ["verify", FIX / "dupe4plus1-pre.txt", "--live", "--require-paths", "4"]),
        ("A11-dupe4plus1-req5-caught",
         ["verify", FIX / "dupe4plus1-pre.txt", "--live", "--require-paths", "5"]),
        ("A12-aliased-symlink-pair-req5",
         ["verify", FIX / "symlink-alias-5stanzas-pre.txt", "--live", "--require-paths", "5"]),
    ]

    lines = ["# EX-25 attack battery — phase=%s  tool=%s" % (phase, tool),
             "# tool sha256: %s" % tool_sha, ""]
    rows = []
    for name, args in attacks:
        cmd = ["python3", str(tool)] + [str(a) for a in args]
        p = subprocess.run(cmd, capture_output=True, text=True)
        lines += ["=" * 78, "ATTACK %s  exit=%d" % (name, p.returncode),
                  "CMD %s" % " ".join(cmd),
                  (p.stdout + (("\n[stderr]\n" + p.stderr) if p.stderr else "")).rstrip("\n"), ""]
        cov = [l for l in (p.stdout + p.stderr).splitlines() if "REFERENCE-COVERAGE" in l]
        rows.append((name, p.returncode, cov[0] if cov else "(no coverage line)"))
    (outdir / "attacks.out").write_text("\n".join(lines), encoding="utf-8")
    print("# tool sha256 %s" % tool_sha)
    for name, rc, cov in rows:
        print("%-42s exit=%-3d %s" % (name, rc, cov))
    return 0


if __name__ == "__main__":
    sys.exit(main())
