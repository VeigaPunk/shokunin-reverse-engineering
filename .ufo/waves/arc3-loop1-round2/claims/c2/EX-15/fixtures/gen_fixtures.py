#!/usr/bin/env python3
"""EX-15 fixture generator — census fail-closure fixture pack (arc3-loop1-round2, chain c2).

Builds hermetic scratch roots (three scoped files only) plus a fake HOME, for
testing the two declared new fail classes of the C2 claim:
  H1 class  — absent / unreadable scoped file must FAIL with a declared class
              (round-1 debt H1; patch text RV-11/proposed-missing-file-guard.patch.md)
  H3 class  — a non-empty scope with zero loci must FAIL the positive-floor
              assertion (round-1 debt H3; patch text CR-5/proposed-g2-positive-floor.patch.md)

Design rules:
  * The blind base is DERIVED from the instrument, not hard-coded: the SCOPE
    table is parsed out of the instrument text, every DATED row's marker regex
    is re-checked against the marker text this generator places at the declared
    line.  A re-keyed SCOPE table that moves a marker line makes this generator
    fail loudly instead of emitting a broken tree.
  * The base carries zero gate-token matches (scan proven against the
    instrument's own REA_GATE pattern, parsed from the instrument text), so the
    H3 fixture is generated by a *legitimate* tree that finds nothing — the
    data-side twin of round-1 CR-5's needle-neutered instrument attack.
  * Anchors are hermetic: a fake HOME pins all three clients to rea-agents@9.9.9,
    so every case outcome is independent of the live custody configs and of the
    repo files' content drift.  (Read-only use of the repo: copies only.)
  * This generator never writes outside its --dest tree.

Usage:
  python3 gen_fixtures.py [--instrument .ufo/gates/c1-census-v10.py]
                          [--dest <this dir>/roots] [--check-only]
Writes <dest>/<case>/PROVINCE.md|SKILL.md|SCORECARD.md and <dest>/../fakehome/.
Exit 0 iff all self-checks pass (marker placement, token scan, sha manifest).
"""
import argparse, ast, hashlib, os, re, sys

FILES = ("PROVINCE.md", "SKILL.md", "SCORECARD.md")

# Marker text placed at each DATED row's declared marker line.  Chosen to
# satisfy the row's own marker regex and to carry NO gate token.
MARKER_TEXT = {
    ("PROVINCE.md", 40): "verified on this host 2026-10-13",
    ("PROVINCE.md", 45): "dated record filed 2026-10-13",
    ("PROVINCE.md", 119): "verified 2026-10-13",
    ("SCORECARD.md", 273): "dated band opened 2026-10-16",
    ("SCORECARD.md", 417): "dated band opened 2026-10-16",
    ("SCORECARD.md", 467): "dated band opened 2026-10-16",
    ("SCORECARD.md", 503): "dated band opened 2026-10-16",
    ("SCORECARD.md", 534): "dated band opened 2026-10-16",
    ("SCORECARD.md", 619): "luna-round-3 record",
    ("SCORECARD.md", 620): "luna-round-4 record",
    ("SCORECARD.md", 636): "dated band opened 2026-10-18",
    ("SCORECARD.md", 704): "arc2-loop1-round2 dated band",
    ("SCORECARD.md", 769): "arc2-loop1-round3 dated band",
}

TISSUE = "calibration note %04d: no statement of record."

# Case-specific content lines, all inside declared ranges.
# Per-file loud controls: the r9 floor is PER READABLE FILE, so a legitimate
# fixture tree needs >= 1 current-ok locus in each file it ships.
PROV_CTL = "omp pin rea-agents@9.9.9 receipt 2026-10-19 alignment note."   # PROVINCE 15-26 CURRENT -> current-ok
SKILL_CTL = "omp pin rea-agents@9.9.9 receipt 2026-10-19 alignment note."  # SKILL 18-20 CURRENT    -> current-ok
CTL = "omp pin rea-agents@9.9.9 receipt 2026-10-19 alignment note."        # SCORECARD 56-60 CURRENT -> current-ok
HIST_PIN = "The r4 record shows rea-agents@6.4.0 on the previous host."    # SCORECARD 703-768 DATED  -> historical
H2_LINE = "The omp client is documented as pinned to rea-agents@9.9.8 (superseded 2026-10-13)."  # inline-marker excusal (H2 probe)
H5_LINE = "The build shipped 6.7.0 last week."                             # gate-free statement (H5 probe)

LOUD = {"PROVINCE.md": {20: PROV_CTL}, "SKILL.md": {19: SKILL_CTL},
        "SCORECARD.md": {58: CTL}}


def merged(*overrides):
    """LOUD controls per file, then per-file REPLACEMENT for the overridden files
    (a replacement can be {} to blank a file's loci)."""
    extra = {f: dict(v) for f, v in LOUD.items()}
    for f, v in overrides:
        extra[f] = dict(v)
    return extra


CASES = {
    # case name            omitted files       zero-byte files  extra content lines
    # --- H3 class (blind scope / floor) ---
    "blind-nonempty":      ((),                (),               {}),
    "partial-blind-skill": ((),                (),               merged(("SKILL.md", {}))),
    "hist-only":           ((),                (),               merged(("SCORECARD.md", {710: HIST_PIN}))),
    # --- controls ---
    "current-ok-ctl":      ((),                (),               merged()),
    # --- H1 class (unreadable, isolated from the floor by loud survivors) ---
    "miss-skill":          (("SKILL.md",),     (),               merged()),
    "miss-province":       (("PROVINCE.md",),  (),               merged()),
    "miss-scorecard":      (("SCORECARD.md",), (),               merged()),
    "empty-skill":         ((),                ("SKILL.md",),    merged()),
    # --- advisory probes ---
    "h2-inline-excuse":    ((),                (),               merged(("SCORECARD.md", {58: CTL, 60: H2_LINE}))),
    "fold-mixed-block":    ((),                (),               merged(("SCORECARD.md", {58: CTL, 59: H2_LINE}))),
    "h5-gate-free":        ((),                (),               merged(("SCORECARD.md", {58: CTL, 60: H5_LINE}))),
}

FAKEHOME = {
    ".config/devin/mcp_config.json": '{"mcpServers":{"rea":{"args":["rea-agents@9.9.9"]}}}\n',
    ".omp/agent/mcp.json":           '{"mcpServers":{"rea":{"args":["rea-agents@9.9.9"]}}}\n',
    ".kimi-code/config.toml":        '[mcp_servers.rea]\ncommand = "npx"\nargs = ["rea-agents@9.9.9"]\n',
}


def parse_scope(txt):
    m = re.search(r"SCOPE\s*=\s*\[(.*?)\n\]", txt, re.S)
    assert m, "SCOPE table not found in instrument"
    rows = []
    for mm in re.finditer(
            r'\(\s*"([^"]+)",\s*(\d+),\s*(\d+),\s*"([A-Z]+)",\s*(None|\d+),\s*(None|r"[^"]*")\s*\)',
            m.group(1)):
        f, s, e, cls, ml, mr = mm.groups()
        if mr and mr != "None" and mr.startswith('r"'):
            mr = mr[2:-1]          # strip the r"..." quoting: keep the pattern text
        rows.append((f, int(s), int(e), cls,
                     None if ml == "None" else int(ml),
                     None if mr == "None" else mr))
    assert rows, "SCOPE table parsed empty"
    return rows


def parse_gate(txt):
    m = re.search(r'REA_GATE\s*=\s*re\.compile\(((?:r)?"(?:\\.|[^"\\])*")', txt)
    assert m, "REA_GATE pattern not found in instrument"
    return re.compile(ast.literal_eval(m.group(1)), re.I)


def natural_len(rows, fname):
    ends = [e for (f, s, e, c, ml, mr) in rows if f == fname]
    assert ends, "no SCOPE rows for %s" % fname
    return max(ends)


def build_file(rows, fname, extra):
    n = natural_len(rows, fname)
    lines = [""] * n
    specified = set(extra)
    for (f, s, e, cls, ml, mr) in rows:
        if f != fname or mr is None:
            continue
        text = MARKER_TEXT[(f, ml)]
        assert re.search(mr, text), "marker text %r fails row regex %r" % (text, mr)
        lines[ml - 1] = text
        specified.add(ml)
    for L in range(1, n + 1):
        if L in specified or any(abs(L - k) <= 1 for k in specified):
            continue
        if L % 7 == 0:
            lines[L - 1] = TISSUE % L
    for L, text in extra.items():
        assert 1 <= L <= n, "extra line %d beyond natural length %d" % (L, n)
        lines[L - 1] = text
    return lines


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    repo = os.path.abspath(os.path.join(here, "..", "..", "..", "..", "..", "..", ".."))
    ap = argparse.ArgumentParser()
    ap.add_argument("--instrument",
                    default=os.path.join(repo, ".ufo/gates/c1-census-v10.py"))
    ap.add_argument("--dest", default=os.path.join(os.path.dirname(os.path.abspath(__file__)), "roots"))
    ap.add_argument("--check-only", action="store_true")
    args = ap.parse_args()

    itxt = open(args.instrument, encoding="utf-8").read()
    rows = parse_scope(itxt)
    gate = parse_gate(itxt)
    print("instrument %s sha256=%s rows=%d" %
          (args.instrument, hashlib.sha256(itxt.encode()).hexdigest(), len(rows)))

    problems = []
    manifest = []
    for case, (omit, empty, extra) in sorted(CASES.items()):
        cdir = os.path.join(args.dest, case)
        if not args.check_only:
            os.makedirs(cdir, exist_ok=True)
        for fname in FILES:
            if fname in omit:
                continue
            file_extra = extra.get(fname, {})
            lines = build_file(rows, fname, file_extra)
            if fname in empty:
                lines = []
            text = "\n".join(lines) + "\n"
            # token scan: generated text must carry no gate token outside the
            # declared extra lines (which are case-intentional).
            intended = set(file_extra)
            for i, line in enumerate(lines, 1):
                if gate.search(line) and i not in intended:
                    problems.append("%s/%s:%d gate token in unintended line: %r" %
                                    (case, fname, i, line[:60]))
            path = os.path.join(cdir, fname)
            if not args.check_only:
                open(path, "w", encoding="utf-8").write(text)
            manifest.append("%s  %s  %s" % (hashlib.sha256(text.encode()).hexdigest(),
                                            "%s/%s" % (case, fname), len(text)))
        print("case %-20s omit=%s empty=%s extra=%s" %
              (case, list(omit), list(empty),
               {f: sorted(v) for f, v in sorted(extra.items())}))

    fhdir = os.path.join(os.path.dirname(os.path.abspath(args.dest)), "fakehome")
    for rel, text in sorted(FAKEHOME.items()):
        path = os.path.join(fhdir, rel)
        if not args.check_only:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            open(path, "w", encoding="utf-8").write(text)
        manifest.append("%s  %s" % (hashlib.sha256(text.encode()).hexdigest(), "fakehome/" + rel))

    if not args.check_only:
        with open(os.path.join(os.path.dirname(os.path.abspath(args.dest)), "manifest.sha256"),
                  "w", encoding="utf-8") as fh:
            fh.write("\n".join(manifest) + "\n")
    if problems:
        print("SELF-CHECK FAILED:")
        for p in problems:
            print("  " + p)
        return 1
    print("SELF-CHECK OK: %d files, markers placed per parsed SCOPE, no stray gate tokens"
          % len(manifest))
    return 0


if __name__ == "__main__":
    sys.exit(main())
