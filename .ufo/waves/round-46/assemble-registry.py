#!/usr/bin/env python3
"""Assemble the round-46 registry section from the wave-1 seat drafts (L1 artifact).

Reads `.ufo/waves/round-46/w1/R46W1Reg*/rows.md`, validates every candidate row against
the frozen predicate (7 cells; cell 0 is exactly one backticked census path; the
verdict-map cell binds 0=, 1= and 2=; no literal pipe inside a cell), and emits the
`### Round-46 instrument registry` section with the two markers. A census path with no
valid row is reported, never invented.
"""
import json
import os
import re
import sys

ROOT = "/home/vgpnk/Projects/shokunin/kaidoku-shokunin"
WAVE = os.path.join(ROOT, ".ufo/waves/round-46/w1")
CENSUS = os.path.join(ROOT, "tools/round-46/census.json")
HEAD = "<!-- instrument-registry v2 -->"
TAIL = "<!-- /instrument-registry -->"
HOUSE = ["tool", "gate or probe - purpose", "verdict map (exit codes)",
         "self-test command", "pinned-value path", "write scope", "owner"]
EXITMAP = re.compile(r"\b([012])\s*[=:]")
CELL0 = re.compile(r"^`(tools/[A-Za-z0-9._/-]+\.(?:py|sh))`$")


def candidates():
    rows = []
    for seat in sorted(os.listdir(WAVE)) if os.path.isdir(WAVE) else []:
        if not seat.startswith("R46W1Reg"):
            continue
        for name in ("rows.md", "row.md", "report.md"):
            path = os.path.join(WAVE, seat, name)
            if not os.path.exists(path):
                continue
            for line in open(path):
                s = line.strip()
                if not s.startswith("| `tools/"):
                    continue
                cells = [c.strip() for c in s.strip().strip("|").split("|")]
                rows.append({"seat": seat, "file": name, "cells": cells, "line": s})
            break
    extra = os.path.join(ROOT, ".ufo/waves/round-46/l1/registry-extra.md")
    if os.path.exists(extra):
        for line in open(extra):
            t = line.strip()
            if not t.startswith("| `tools/"):
                continue
            rows.append({"seat": "L1-extra", "file": "registry-extra.md",
                         "cells": [c.strip() for c in t.strip().strip("|").split("|")],
                         "line": t})
    return rows


def main():
    census = json.load(open(CENSUS))["paths"]
    seen, good, bad = {}, [], []
    for row in candidates():
        cells = row["cells"]
        if len(cells) != 7:
            bad.append((row, f"{len(cells)} cells"))
            continue
        m = CELL0.match(cells[0])
        if not m or m.group(1) not in census:
            bad.append((row, "cell 0 is not exactly one census path"))
            continue
        if set(EXITMAP.findall(cells[2])) != {"0", "1", "2"}:
            bad.append((row, "verdict map does not bind 0=, 1= and 2="))
            continue
        path = m.group(1)
        if path in seen:
            continue
        seen[path] = row
        good.append(row)
    missing = [p for p in census if p not in seen]
    out = []
    out.append("### Round-46 instrument registry\n")
    out.append(
        "Added round 46. Round 45 registered the six instruments of rounds 44–45; this\n"
        "section registers the whole census `tools/round-46/census.json`, generated by\n"
        "`tools/round-46/census.py` from every `tools/round-4[1-6]/**.{py,sh}` path the\n"
        "round-41..46 claim files name and which exists at the measured revision. The\n"
        "section is bound by its two markers, so nothing outside it, inside a fence or\n"
        "inside an HTML comment registers; cell 1 is exact path equality and cell 3 binds\n"
        "each of 0, 1 and 2 to its meaning. `tools/round-46/registry.py` scores it and\n"
        "`absent_at_rev` proves each named tool exists at the measured revision.\n")
    out.append(HEAD + "\n")
    out.append("| " + " | ".join(HOUSE) + " |")
    out.append("|" + "---|" * len(HOUSE))
    for p in census:
        row = seen.get(p)
        out.append(row["line"] if row else "| `%s` | UNREGISTERED | 0= | none | none | none | kaidoku |" % p)
    out.append("")
    out.append(TAIL + "\n")
    text = "\n".join(out)
    dest = os.path.join(ROOT, ".ufo/waves/round-46/l1/registry-section.md")
    os.makedirs(os.path.dirname(dest), exist_ok=True)
    with open(dest, "w") as fh:
        fh.write(text)
    print(json.dumps({"census": len(census), "rows_used": len(good),
                      "rejected": len(bad), "missing": missing,
                      "out": dest}, indent=1))
    for row, why in bad[:20]:
        print("REJECT", row["seat"], row["file"], why, row["line"][:120])
    return 0 if not missing else 1


if __name__ == "__main__":
    sys.exit(main())
